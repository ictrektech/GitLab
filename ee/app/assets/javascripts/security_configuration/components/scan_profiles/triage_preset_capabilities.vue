<script>
import { GlButton, GlIcon, GlPopover } from '@gitlab/ui';
import { uniqueId } from 'lodash-es';
import { s__, sprintf } from '~/locale';
import { TRIAGE_PRESET_CAPABILITY_GROUPS } from 'ee/security_configuration/constants';

const CAPABILITY_DETAILS = {
  SAST_FALSE_POSITIVE: {
    description: s__(
      'ScanProfiles|Flags likely false positives, reviewing each SAST vulnerability.',
    ),
    note: s__('ScanProfiles|Analysis is performed by AI.'),
  },
  SAST_VULNERABILITY_RESOLUTION: {
    description: s__('ScanProfiles|Opens a fix merge request that rewrites vulnerable code.'),
    note: s__('ScanProfiles|Fixes are generated by AI.'),
  },
  SBOM_INGESTED: {
    description: s__(
      'ScanProfiles|Opens a fix merge request that updates the dependency to a safe version.',
    ),
    note: s__('ScanProfiles|Updates the dependency version without AI, so no credits are spent.'),
  },
  SECRET_DETECTION_FALSE_POSITIVE: {
    description: s__('ScanProfiles|Flags likely false positives, reviewing each detected secret.'),
    note: s__('ScanProfiles|Analysis is performed by AI.'),
  },
};

const CAPABILITY_GROUPS = TRIAGE_PRESET_CAPABILITY_GROUPS.map((group) => ({
  ...group,
  capabilities: group.capabilities.map((capability) => ({
    ...capability,
    ...CAPABILITY_DETAILS[capability.triggerType],
  })),
}));

export default {
  name: 'TriagePresetCapabilities',
  components: {
    GlButton,
    GlIcon,
    GlPopover,
  },
  props: {
    triggers: {
      type: Array,
      required: true,
    },
  },
  data() {
    return { helpTargetIdPrefix: uniqueId('triage-preset-capability-help-') };
  },
  computed: {
    capabilityGroups() {
      return CAPABILITY_GROUPS.map((group) => ({
        ...group,
        capabilities: group.capabilities.filter(({ triggerType }) =>
          this.triggers.includes(triggerType),
        ),
      })).filter((group) => group.capabilities.length);
    },
  },
  methods: {
    helpTargetId({ triggerType }) {
      return `${this.helpTargetIdPrefix}-${triggerType}`;
    },
    helpLabel({ title }) {
      return sprintf(s__('ScanProfiles|About %{capability}'), { capability: title });
    },
  },
};
</script>

<template>
  <div class="gl-flex gl-flex-col gl-gap-5">
    <section v-for="group in capabilityGroups" :key="group.title">
      <h4 class="gl-heading-4 gl-mb-3">{{ group.title }}</h4>
      <ul class="gl-m-0 gl-flex gl-list-none gl-flex-col gl-gap-3 gl-p-0">
        <li
          v-for="capability in group.capabilities"
          :key="capability.triggerType"
          class="gl-flex gl-items-center gl-gap-2 gl-rounded-xl gl-bg-strong gl-px-5 gl-py-4"
          :data-testid="`capability-${capability.triggerType}`"
        >
          <gl-icon :name="capability.icon" :size="16" />
          <h5 class="gl-heading-5 gl-mb-0">{{ capability.title }}</h5>
          <gl-button
            :id="helpTargetId(capability)"
            category="tertiary"
            size="small"
            icon="information-o"
            :aria-label="helpLabel(capability)"
          />
          <gl-popover :target="helpTargetId(capability)">
            <p class="gl-mb-0">{{ capability.description }}</p>
            <p class="gl-mb-0 gl-mt-2 gl-text-sm gl-text-subtle">{{ capability.note }}</p>
          </gl-popover>
        </li>
      </ul>
    </section>
  </div>
</template>
